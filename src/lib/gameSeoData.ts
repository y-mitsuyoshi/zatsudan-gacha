export function buildGameJsonLd(game: GameSeoData) {
  const url = `${APP_URL}${game.slug}`;
  const image = `${APP_URL}${game.image}`;

  const videoGame = {
    '@context': 'https://schema.org',
    '@type': 'VideoGame',
    name: game.name,
    description: game.description,
    url,
    image,
    genre: game.genre,
    gamePlatform: 'Web browser',
    applicationCategory: 'GameApplication',
    operatingSystem: 'Any',
    inLanguage: 'ja-JP',
    isAccessibleForFree: true,
    offers: {
      '@type': 'Offer',
      price: '0',
      priceCurrency: 'JPY',
    },
    publisher: { '@id': `${APP_URL}/#organization` },
  };

  const faqPage = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: game.faqs.map((faq) => ({
      '@type': 'Question',
      name: faq.q,
      acceptedAnswer: {
        '@type': 'Answer',
        text: faq.a,
      },
    })),
  };

  return [videoGame, faqPage];
}
