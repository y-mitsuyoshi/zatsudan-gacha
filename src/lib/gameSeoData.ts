export function buildGameJsonLd(game: GameSeoData) {
  const url = `${APP_URL}${game.slug}`;
  const image = `${APP_URL}${game.image}`;

  const videoGame = {
    '@context': 'https://schema.org',
    '@type': 'VideoGame',
    '@id': `${url}#videogame`,
    name: game.name,
    headline: game.h1,
    description: game.description,
    url,
    image,
    screenshot: image,
    genre: game.genre,
    playMode: 'SinglePlayer',
    gamePlatform: ['Web browser', 'Desktop Web Browser', 'Mobile Web Browser'],
    applicationCategory: 'GameApplication',
    operatingSystem: 'Any',
    inLanguage: 'ja-JP',
    isAccessibleForFree: true,
    isPartOf: { '@id': `${APP_URL}/#website` },
    offers: {
      '@type': 'Offer',
      price: '0',
      priceCurrency: 'JPY',
      availability: 'https://schema.org/InStock',
    },
    publisher: { '@id': `${APP_URL}/#organization` },
  };

  const webApp = {
    '@context': 'https://schema.org',
    '@type': 'WebApplication',
    '@id': `${url}#webapp`,
    name: game.name,
    description: game.description,
    url,
    image,
    screenshot: image,
    applicationCategory: 'GameApplication',
    browserRequirements: 'Requires HTML5 Canvas and JavaScript',
    operatingSystem: 'Any',
    inLanguage: 'ja-JP',
    isAccessibleForFree: true,
    offers: {
      '@type': 'Offer',
      price: '0',
      priceCurrency: 'JPY',
    },
    publisher: { '@id': `${APP_URL}/#organization` },
  };

  const howTo = {
    '@context': 'https://schema.org',
    '@type': 'HowTo',
    '@id': `${url}#howto`,
    name: `${game.name}の遊び方`,
    description: game.description,
    inLanguage: 'ja-JP',
    step: game.steps.map((step, index) => ({
      '@type': 'HowToStep',
      position: index + 1,
      name: step.title,
      text: step.text,
    })),
  };

  const faqPage = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    '@id': `${url}#faq`,
    mainEntity: game.faqs.map((faq) => ({
      '@type': 'Question',
      name: faq.q,
      acceptedAnswer: {
        '@type': 'Answer',
        text: faq.a,
      },
    })),
  };

  return [videoGame, webApp, howTo, faqPage];
}
